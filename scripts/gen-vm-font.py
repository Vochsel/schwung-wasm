"""Turn Schwung's host bitmap font (font.png + .dat char list, 5x7 cells) into
engine/vm_font.h for Virtual Move's own screen. Run via:
uv run --no-project --with pillow==11.3.0 python3 scripts/gen-vm-font.py build/vfs-base/data/UserData/schwung/host/font.png"""
import sys
from PIL import Image
png = sys.argv[1]
chars = open(png + '.dat', encoding='utf-8').read().rstrip('\n')
im = Image.open(png).convert('RGBA')
w, h = im.size
cw = w // len(chars)
cols = {}
for i, ch in enumerate(chars):
    if not (32 <= ord(ch) < 127):
        continue
    out = []
    for x in range(cw):
        b = 0
        for y in range(h):
            if im.getpixel((i * cw + x, y))[3] > 0:
                b |= 1 << y
        out.append(b)
    cols[ord(ch)] = out
with open('engine/vm_font.h', 'w') as f:
    f.write('/* Generated by scripts/gen-vm-font.py from Schwung\'s host/font.png (MIT). */\n')
    f.write(f'#define VM_FONT_W {cw}\n#define VM_FONT_H {h}\n')
    f.write(f'static const unsigned char vm_font[95][{cw}] = {{\n')
    for c in range(32, 127):
        f.write('  {' + ','.join(str(v) for v in cols.get(c, [0] * cw)) + '},\n')
    f.write('};\n')
print('engine/vm_font.h', len(cols), 'glyphs', cw, 'x', h)
