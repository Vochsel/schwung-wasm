#!/usr/bin/env python3
"""Procedurally synthesise a tiny demo sample kit for sample-based modules.
Original content generated by schwung-wasm (no third-party audio); CC0-1.0.
usage: gen_demo_samples.py <out_dir>   -> 44.1 kHz 16-bit WAVs:
  kick.wav snare.wav hat.wav clap.wav (mono), keys-C4.wav, pad-C3.wav (stereo),
  loop-120bpm.wav (stereo, 2 bars)."""
import math, os, random, struct, sys

SR = 44100
rnd = random.Random(1234)

def write(path, frames, ch=1):
    data = b''.join(struct.pack('<' + 'h' * ch, *[max(-32767, min(32767, int(s * 32767))) for s in f]) for f in frames)
    with open(path, 'wb') as fp:
        fp.write(b'RIFF' + struct.pack('<I', 36 + len(data)) + b'WAVEfmt ' +
                 struct.pack('<IHHIIHH', 16, 1, ch, SR, SR * 2 * ch, 2 * ch, 16) + b'data' + struct.pack('<I', len(data)) + data)

def kick(n=int(0.5 * SR)):
    ph = 0.0
    for i in range(n):
        t = i / SR
        f = 45 + 120 * math.exp(-t * 30)
        ph += 2 * math.pi * f / SR
        yield (0.95 * math.sin(ph) * math.exp(-t * 6),)

def snare(n=int(0.3 * SR)):
    for i in range(n):
        t = i / SR
        yield (0.5 * math.sin(2 * math.pi * 190 * t) * math.exp(-t * 25) + 0.6 * (rnd.random() * 2 - 1) * math.exp(-t * 14),)

def hat(n=int(0.12 * SR)):
    prev = 0.0
    for i in range(n):
        x = rnd.random() * 2 - 1
        y = x - prev; prev = x  # crude high-pass
        yield (0.45 * y * math.exp(-i / SR * 40),)

def clap(n=int(0.35 * SR)):
    for i in range(n):
        t = i / SR
        env = sum(math.exp(-(t - d) * 120) for d in (0, 0.01, 0.022) if t >= d) * 0.3 + 0.4 * math.exp(-t * 12)
        yield (0.6 * (rnd.random() * 2 - 1) * min(env, 1.0),)

def tone(freq, secs, decay, harm):
    n = int(secs * SR)
    for i in range(n):
        t = i / SR
        s = sum(a * math.sin(2 * math.pi * freq * k * t) for k, a in harm) * math.exp(-t * decay)
        s *= min(1.0, t * 200)
        yield (s * 0.9, s * 0.85)

def loop():
    beat = SR // 2  # 120 BPM
    out = [[0.0, 0.0] for _ in range(beat * 8)]
    def add(gen, at, g=1.0):
        for j, f in enumerate(gen):
            if at + j < len(out):
                out[at + j][0] += f[0] * g; out[at + j][1] += f[-1] * g
    for b in range(8):
        add(kick(), b * beat, 0.9)
        add(hat(), b * beat + beat // 2, 0.7)
        if b % 2: add(snare(), b * beat, 0.8)
    return out

d = sys.argv[1]
os.makedirs(d, exist_ok=True)
write(os.path.join(d, 'kick.wav'), kick())
write(os.path.join(d, 'snare.wav'), snare())
write(os.path.join(d, 'hat.wav'), hat())
write(os.path.join(d, 'clap.wav'), clap())
write(os.path.join(d, 'keys-C4.wav'), tone(261.63, 2.0, 1.5, [(1, 0.5), (2, 0.25), (3, 0.12), (4, 0.06)]), 2)
write(os.path.join(d, 'pad-C3.wav'), tone(130.81, 3.0, 0.3, [(1, 0.4), (1.005, 0.3), (2, 0.15), (3, 0.08)]), 2)
write(os.path.join(d, 'loop-120bpm.wav'), loop(), 2)
with open(os.path.join(d, 'LICENSE.txt'), 'w') as fp:
    fp.write('Procedurally generated by schwung-wasm modules/demo/gen_demo_samples.py. CC0-1.0 (public domain).\n')
