#!/usr/bin/env python3
"""Write a minimal valid SoundFont 2 (one preset, one instrument, one looped
sample of a soft saw/organ tone at ~C4). Original content generated by
schwung-wasm; CC0-1.0.  usage: gen_demo_sf2.py <out.sf2>"""
import math, struct, sys

SR, CYCLE = 44100, 168            # 168-sample cycle = 262.5 Hz (C4 + ~5.7 c)
N = SR                             # 1 s sample, loop over the second half
smp = []
for i in range(N):
    ph = (i % CYCLE) / CYCLE
    s = sum(math.sin(2 * math.pi * k * ph) / k for k in range(1, 9)) * 0.35
    env = min(1.0, i / 200.0)
    smp.append(int(max(-1, min(1, s * env)) * 30000))
loop_s, loop_e = N // 2, N // 2 + CYCLE * 100

def ck(tag, data):
    if len(data) & 1: data += b'\0'
    return tag + struct.pack('<I', len(data)) + data
def lst(tag, *chunks): return ck(b'LIST', tag + b''.join(chunks))
def name(s, n=20): return s.encode()[:n - 1].ljust(n, b'\0')

info = lst(b'INFO', ck(b'ifil', struct.pack('<HH', 2, 1)), ck(b'isng', b'EMU8000\0'),
           ck(b'INAM', b'schwung-wasm demo\0'), ck(b'ICOP', b'CC0-1.0 schwung-wasm\0'))
sdta = lst(b'sdta', ck(b'smpl', struct.pack('<%dh' % (N + 46), *(smp + [0] * 46))))
phdr = struct.pack('<20sHHHIII', name('Demo Organ'), 0, 0, 0, 0, 0, 0) + struct.pack('<20sHHHIII', name('EOP'), 0, 0, 1, 0, 0, 0)
pbag = struct.pack('<HH', 0, 0) + struct.pack('<HH', 1, 0)
pmod = b'\0' * 10
pgen = struct.pack('<HH', 41, 0) + struct.pack('<HH', 0, 0)
inst = struct.pack('<20sH', name('Demo Organ'), 0) + struct.pack('<20sH', name('EOI'), 1)
ibag = struct.pack('<HH', 0, 0) + struct.pack('<HH', 4, 0)
imod = b'\0' * 10
igen = (struct.pack('<HBB', 43, 0, 127) +          # keyRange 0-127
        struct.pack('<Hh', 38, -2400) +            # releaseVolEnv ~0.25 s
        struct.pack('<HH', 54, 1) +                # sampleModes: loop
        struct.pack('<HH', 53, 0) +                # sampleID 0
        struct.pack('<HH', 0, 0))
shdr = (struct.pack('<20sIIIIIBbHH', name('organ-c4'), 0, N, loop_s, loop_e, SR, 60, -6, 0, 1) +
        struct.pack('<20sIIIIIBbHH', name('EOS'), 0, 0, 0, 0, 0, 0, 0, 0, 0))
pdta = lst(b'pdta', ck(b'phdr', phdr), ck(b'pbag', pbag), ck(b'pmod', pmod), ck(b'pgen', pgen),
           ck(b'inst', inst), ck(b'ibag', ibag), ck(b'imod', imod), ck(b'igen', igen), ck(b'shdr', shdr))
body = b'sfbk' + info + sdta + pdta
open(sys.argv[1], 'wb').write(b'RIFF' + struct.pack('<I', len(body)) + body)
